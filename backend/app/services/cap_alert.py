"""
cap_alert.py  —  Common Alerting Protocol (CAP) v1.2 export. Your deck already claims CAP;
this makes it real in ~150 lines. India's SACHET alerting platform is CAP-based, so this is
the format an SDMA/DDMA can actually ingest.

Human-in-the-loop is built into the protocol itself:
  status="Draft"  -> generated by TerraSentinel, NOT public
  status="Actual" -> only after an authorised officer approves (approve() below)
  status="Exercise" -> for demos / drills  (USE THIS AT THE HACKATHON)

Usage:
  python cap_alert.py   # writes demo_alert.xml (Exercise) and validates it
"""
from __future__ import annotations

import datetime as dt
import math
import uuid
import xml.etree.ElementTree as ET
from typing import Dict, List, Optional, Tuple

CAP_NS = "urn:oasis:names:tc:emergency:cap:1.2"
ET.register_namespace("", CAP_NS)

# risk level -> (urgency, severity, certainty, responseType)
LEVEL_MAP = {
    "CRITICAL": ("Immediate", "Extreme", "Likely", "Evacuate"),
    "HIGH":     ("Expected", "Severe", "Likely", "Prepare"),
    "MODERATE": ("Future", "Moderate", "Possible", "Monitor"),
    "LOW":      ("Future", "Minor", "Unlikely", "Monitor"),
}

# Instruction text per level. Translations MUST be reviewed by a native speaker before real use.
INSTRUCTIONS = {
    "en-IN": {
        "CRITICAL": "Landslide risk is extreme. Move away from steep slopes and stream channels now. Avoid travel on {road}.",
        "HIGH": "High landslide risk in the next hours. Avoid non-essential travel on {road}. Watch for cracks, tilting trees, muddy water.",
        "MODERATE": "Moderate landslide risk. Stay alert to official updates and report cracks or falling rocks.",
        "LOW": "Low landslide risk. No action needed.",
    },
}


def _t(parent, tag, text=None):
    el = ET.SubElement(parent, f"{{{CAP_NS}}}{tag}")
    if text is not None:
        el.text = str(text)
    return el


def circle_polygon(lat: float, lon: float, radius_km: float, n: int = 16) -> str:
    """CAP polygon string 'lat,lon lat,lon ...' (closed: first == last)."""
    pts = []
    for k in range(n):
        a = 2 * math.pi * k / n
        dlat = (radius_km / 111.32) * math.cos(a)
        dlon = (radius_km / (111.32 * math.cos(math.radians(lat)))) * math.sin(a)
        pts.append(f"{lat + dlat:.4f},{lon + dlon:.4f}")
    pts.append(pts[0])
    return " ".join(pts)


def build_alert(level: str, lat: float, lon: float, area_desc: str, risk: float,
                road: str = "nearby roads", radius_km: float = 3.0, status: str = "Draft",
                sender: str = "terrasentinel@example.org", expires_hours: int = 12,
                explanation: Optional[Dict] = None, languages: List[str] = ("en-IN",)) -> str:
    if level not in LEVEL_MAP:
        raise ValueError(level)
    if status not in ("Actual", "Exercise", "System", "Test", "Draft"):
        raise ValueError(status)
    now = dt.datetime.now(dt.timezone(dt.timedelta(hours=5, minutes=30))).replace(microsecond=0)
    urgency, severity, certainty, response = LEVEL_MAP[level]

    alert = ET.Element(f"{{{CAP_NS}}}alert")
    _t(alert, "identifier", f"TS-{now:%Y%m%d%H%M%S}-{uuid.uuid4().hex[:8]}")
    _t(alert, "sender", sender)
    _t(alert, "sent", now.isoformat())
    _t(alert, "status", status)
    _t(alert, "msgType", "Alert")
    _t(alert, "scope", "Public")
    if status == "Draft":
        _t(alert, "note", "Machine-generated draft. Requires SDMA/DDMA officer approval before release.")
    for lang in languages:
        info = _t(alert, "info")
        _t(info, "language", lang)
        _t(info, "category", "Geo")
        _t(info, "event", "Landslide")
        _t(info, "responseType", response)
        _t(info, "urgency", urgency)
        _t(info, "severity", severity)
        _t(info, "certainty", certainty)
        _t(info, "effective", now.isoformat())
        _t(info, "expires", (now + dt.timedelta(hours=expires_hours)).isoformat())
        _t(info, "senderName", "TerraSentinel Landslide Early Warning (pilot)")
        _t(info, "headline", f"{level.title()} landslide risk - {area_desc}")
        _t(info, "description", f"Computed landslide risk {risk:.2f} ({level}) from rainfall, soil moisture "
                                f"and slope stability analysis.")
        _t(info, "instruction", INSTRUCTIONS.get(lang, INSTRUCTIONS["en-IN"])[level].format(road=road))
        for k, v in {"risk_score": f"{risk:.3f}", **({k: str(v) for k, v in (explanation or {}).items()})}.items():
            p = _t(info, "parameter"); _t(p, "valueName", k); _t(p, "value", v)
        area = _t(info, "area")
        _t(area, "areaDesc", area_desc)
        _t(area, "polygon", circle_polygon(lat, lon, radius_km))
    return ET.tostring(alert, encoding="unicode", xml_declaration=True)


def approve(xml_str: str, officer_id: str) -> str:
    """Officer approval: Draft -> Actual, records who approved. Call ONLY from an authenticated UI."""
    root = ET.fromstring(xml_str)
    st = root.find(f"{{{CAP_NS}}}status")
    if st is None or st.text != "Draft":
        raise ValueError("Only Draft alerts can be approved")
    st.text = "Actual"
    note = root.find(f"{{{CAP_NS}}}note")
    if note is None:                                   # CAP order: note goes right after scope/code
        note = ET.Element(f"{{{CAP_NS}}}note")
        first_info = next((i for i, c in enumerate(root) if c.tag == f"{{{CAP_NS}}}info"), len(root))
        root.insert(first_info, note)
    note.text = f"Approved by {officer_id} at {dt.datetime.now().isoformat(timespec='seconds')}"
    return ET.tostring(root, encoding="unicode", xml_declaration=True)


REQUIRED_ALERT = ["identifier", "sender", "sent", "status", "msgType", "scope"]
REQUIRED_INFO = ["category", "event", "urgency", "severity", "certainty"]


def validate(xml_str: str) -> Tuple[bool, List[str]]:
    """Checks CAP 1.2 required elements + polygon closure. (Use an official XSD for full validation.)"""
    errs = []
    root = ET.fromstring(xml_str)
    if root.tag != f"{{{CAP_NS}}}alert":
        errs.append("root must be cap:alert")
    for tag in REQUIRED_ALERT:
        if root.find(f"{{{CAP_NS}}}{tag}") is None:
            errs.append(f"missing alert/{tag}")
    for info in root.findall(f"{{{CAP_NS}}}info"):
        for tag in REQUIRED_INFO:
            if info.find(f"{{{CAP_NS}}}{tag}") is None:
                errs.append(f"missing info/{tag}")
        for poly in info.iter(f"{{{CAP_NS}}}polygon"):
            pts = poly.text.split()
            if len(pts) < 4 or pts[0] != pts[-1]:
                errs.append("polygon must have >=4 points and be closed")
    return (not errs), errs


